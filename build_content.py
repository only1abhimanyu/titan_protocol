"""Authoring script -> content/*.json

Content is hand-authored on purpose. Every distractor is tagged with the named
misconception it evidences, which is what makes diagnosis possible. LLM
generation is used for *personalisation* at runtime, never for the item bank
itself (quality + determinism matter more than novelty here).
"""
import json, os

OUT = os.path.join(os.path.dirname(__file__), "content")
os.makedirs(OUT, exist_ok=True)


def I(iid, concept, diff, stem, opts, explain):
    # Options may be written as ("text", tag) tuples or as flat text/tag pairs.
    options, i = [], 0
    while i < len(opts):
        if isinstance(opts[i], tuple):
            text, tag = opts[i]
            i += 1
        else:
            text, tag = opts[i], opts[i + 1]
            i += 2
        options.append({"text": text, "correct": tag is True,
                        "misconception": None if tag is True else tag})
    return {"id": iid, "concept": concept, "difficulty": diff,
            "stem": stem, "options": options, "explain": explain}


def C(cid, name, prereqs, summary, analogy, key_ideas):
    return {"id": cid, "name": name, "prereqs": prereqs, "summary": summary,
            "analogy": analogy, "key_ideas": key_ideas}


def M(mid, name, statement, why, repair):
    return {"id": mid, "name": name, "statement": statement, "why": why,
            "repair": repair}


